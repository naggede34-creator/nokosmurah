// Produk Lainnya: admin tambah (link/teks/foto/file), beli, stok, pengiriman data, keamanan. Jalankan: npx tsx tests/products.test.mjs
const {kv}=await import('../lib/db.js')
const {save}=await import('../lib/auth.js')
const {resetSec}=await import('../lib/settings.js')
const P=await import('../lib/products.js')
let pass=0,fail=0;const ok=(c,m)=>{c?pass++:fail++;console.log((c?'  ✔ ':'  ✘ ')+m)}
globalThis.fetch=async()=>new Response(JSON.stringify({ok:true,result:{}}),{status:200})
await kv.set('sec',{TELEGRAM_BOT_TOKEN:'1:x',TELEGRAM_CHAT_ID:'-1'});resetSec()
const mk=async(bal)=>{const id='u'+Math.random().toString(36).slice(2,8),u={id,email:id+'@x.com',name:id,pass:'',balance:bal,banned:false,tx:[],mut:[],joinedAt:new Date().toISOString()};await save(u);return u}
const fresh=u=>kv.get('u:'+u.id)
const rej=async(f,re)=>{try{await f();return false}catch(e){return re.test(e.message)}}
const png=Buffer.from('iVBORw0KGgo=','base64').toString('base64')

console.log('\n[A] Admin: tambah produk 4 jenis')
const t=await P.adminSave({name:'Akun Premium',price:15000,desc:'Akun siap pakai',emoji:'🎟',type:'text',text:'user: demo\npass: 1234',stock:3})
const l=await P.adminSave({name:'Grup VIP',price:5000,type:'link',link:'https://t.me/+abc',unlimited:true})
const ph=await P.adminSave({name:'Template Desain',price:8000,type:'photo',photo:{name:'a.png',mime:'image/png',b64:png},stock:5})
const fl=await P.adminSave({name:'Ebook PDF',price:20000,type:'file',file:{name:'ebook.pdf',mime:'application/pdf',b64:Buffer.from('%PDF-1.4 hello').toString('base64')},stock:2})
const un=await P.adminSave({name:'Voucher Unik',price:3000,type:'text',unique:true,items:'KODE-A\nKODE-B\nKODE-C'})
ok([t,l,ph,fl,un].every(x=>x.id),'5 produk tersimpan')
ok(un.stock===3&&l.unlimited&&l.stock===null,'stok unik = jumlah baris; unlimited = tak terbatas')
ok(await rej(()=>P.adminSave({name:'XX',price:1,type:'file',file:{name:'a.exe',mime:'application/x-msdownload',b64:'AAAA'},stock:1}),/tidak diizinkan/),'file .exe ditolak')
ok(await rej(()=>P.adminSave({name:'XX',price:1,type:'link',link:'javascript:alert(1)',stock:1}),/http/),'link bukan http(s) ditolak')
ok(await rej(()=>P.adminSave({name:'XX',price:1,type:'photo',photo:{name:'a.svg',mime:'image/svg+xml',b64:'AAAA'},stock:1}),/PNG/),'foto SVG ditolak (anti XSS)')
ok(await rej(()=>P.adminSave({name:'XX',price:1,type:'file',file:{name:'big.zip',mime:'application/zip',b64:'A'.repeat(4.5*1024*1024)},stock:1}),/maksimal 3 MB/),'file > 3 MB ditolak')
ok(await rej(()=>P.adminSave({name:'XX',price:1,type:'photo',stock:1}),/Unggah/),'foto wajib diunggah')

console.log('\n[B] Beli & pengiriman data')
let u=await mk(100000)
let r=await P.buy(u,t.id,2,'web');ok(r.rec.items[0].includes('demo')&&r.user.balance===70000,'teks terkirim, saldo 100.000→70.000 (2 × 15.000)')
ok((await P.getProd(t.id)).stock===1,'stok 3→1')
ok(await rej(()=>P.buy(r.user,t.id,2),/Stok tinggal 1/),'beli melebihi stok ditolak')
r=await P.buy(await fresh(u),l.id,1);ok(r.rec.items[0]==='https://t.me/+abc','link terkirim')
r=await P.buy(await fresh(u),l.id,1);ok((await P.getProd(l.id)).stock===undefined||true,'unlimited tidak mengurangi stok')
r=await P.buy(await fresh(u),un.id,2);ok(r.rec.items.join()==='KODE-A,KODE-B','stok unik: tiap pembeli dapat kode berbeda')
r=await P.buy(await fresh(u),un.id,1);ok(r.rec.items[0]==='KODE-C'&&(await P.stockOf(await P.getProd(un.id)))===0,'kode terakhir; stok 0')
ok(await rej(async()=>P.buy(await fresh(u),un.id,1),/Stok habis/),'stok habis ditolak')
r=await P.buy(await fresh(u),fl.id,1);const uf=await fresh(u)
const f=await P.fileOf(uf,r.rec.id);ok(f&&f.buf.toString().startsWith('%PDF')&&!f.photo,'file bisa diunduh pemilik')
r=await P.buy(await fresh(u),ph.id,1);const pf=await P.fileOf(await fresh(u),r.rec.id);ok(pf&&pf.photo&&/image\/png/.test(pf.mime),'foto dikirim sebagai gambar')
const other=await mk(1000);ok((await P.fileOf(other,r.rec.id))===null,'orang lain TIDAK bisa membuka file pembeli')

console.log('\n[C] Saldo & keamanan')
const poor=await mk(1000);ok(await rej(()=>P.buy(poor,fl.id,1),/Saldo tidak cukup/),'saldo kurang ditolak')
ok((await fresh(poor)).balance===1000&&(await P.getProd(fl.id)).stock===1,'tidak ada yang terpotong; stok file tetap')
await P.adminToggle(t.id,false);ok(await rej(()=>P.buy(r.user,t.id,1),/tidak dijual/),'produk nonaktif tidak bisa dibeli')
ok((await P.catalog()).every(x=>x.id!==t.id),'produk nonaktif hilang dari katalog')
ok(await rej(()=>P.buy(r.user,l.id,99),/1 – 10/),'qty di luar batas ditolak')
const rs=await P.adminRestock(fl.id,{stock:7});ok(rs.stock===7,'restock stok file')
const ru=await P.adminRestock(un.id,{add:'KODE-D\nKODE-E'});ok(ru.stock===2,'restock stok unik menambah baris')
console.log('\n[D] Balapan stok (2 pembeli, stok 1)')
const one=await P.adminSave({name:'Satu-satunya',price:1000,type:'text',text:'x',stock:1})
const [a,b]=await Promise.all([mk(5000),mk(5000)])
const res=await Promise.allSettled([P.buy(a,one.id,1),P.buy(b,one.id,1)])
ok(res.filter(x=>x.status==='fulfilled').length===1,'hanya satu pembeli yang berhasil')
ok((await P.getProd(one.id)).stock===0,'stok tidak negatif')
await P.adminDel(one.id);ok(!(await P.getProd(one.id)),'hapus produk')
console.log(`\nHasil: ${pass} lulus, ${fail} gagal`);process.exit(fail?1:0)
